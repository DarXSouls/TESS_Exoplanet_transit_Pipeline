"""
==========================================================
Representation Generation Layer (RGL)

Representation models used by the preprocessing framework.

These dataclasses describe scientific representations
generated by the preprocessing pipeline together with
their transformation lineage.

Author : Shyam Girish Chinta
==========================================================
"""

from __future__ import annotations

from collections import OrderedDict
from dataclasses import dataclass, field
from typing import Any

import pandas as pd

from preprocessing.enums import (
    FluxType,
    RepresentationStatus,
    RepresentationType,
    TransformCategory
)

from collections.abc import Mapping

  
# Transform Step

@dataclass(
    slots=True,
    frozen=True
)
class TransformStep:
    """
    Records one execution of a preprocessing plugin.
    
    Each transform stores the plugin identity,
    its configuration, inputs and outputs,
    allowing complete reconstruction of the
    representation lineage.
    """

    plugin_name: str

    plugin_version: tuple[int, int, int]

    plugin_category: TransformCategory

    transform_parameters: Mapping[str, Any] = field(
        default_factory=dict
    )

    input_columns: tuple[str, ...] = ()

    output_columns: tuple[str, ...] = ()

    execution_order: int = 0

    execution_time_seconds: float | None = None


  
# Representation Columns

@dataclass(
    slots=True
)
class RepresentationColumns:
    """
    Representation-specific columns.

    Only columns generated by the transformation
    pipeline are stored here.

    Shared columns such as TIME, QUALITY, SECTOR,
    etc. remain inside the cleaned dataframe.
    """

    columns: Mapping[
        str,
        pd.Series
    ] = field(
        default_factory=OrderedDict
    )


  
# Representation

@dataclass(
    slots=True,
    frozen=True
)
class Representation:
    """
    Scientific representation of a lightcurve.

    A representation stores
    
    • identity
    • lineage
    • generated columns
    
    Evaluation metrics are stored separately.
    """

    representation_id: str

    display_name: str

    representation_type: RepresentationType

    status: RepresentationStatus

    source_flux: FluxType

    transform_steps: tuple[
        TransformStep,
        ...
    ]

    columns: RepresentationColumns

    primary_flux_column: str

    primary_flux_error_column: str
    
    @property
    def n_transform_steps(self) -> int:
        """
        Number of preprocessing transforms used
        to generate this representation.
        """
        return len(self.transform_steps)