"""
==========================================================
Representation Generation Layer (RGL)

Metric models used by the preprocessing framework.

These dataclasses describe the evaluation of scientific
representations generated by the preprocessing pipeline.

Author : Shyam Girish Chinta
==========================================================
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass


 
# Representation Metrics

@dataclass(
    slots=True,
    frozen=True
)
class RepresentationMetrics:
    """
    Evaluation metrics for a scientific representation.

    This object stores the numerical evaluation of a
    representation without modifying the representation
    itself.

    Notes
    -----
    Metrics are read-only after creation.

    The metric names are intentionally generic so new
    metrics can be introduced without changing the model.
    """

    representation_id: str

    metrics: Mapping[
        str,
        float
    ]

    quality_score: float | None = None

    evaluation_method: str = "default"

    evaluation_version: tuple[int, int, int] = (
        1,
        0,
        0,
    )

    # ------------------------------------------------------

    @property
    def n_metrics(
        self
    ) -> int:
        """
        Number of computed metrics.
        """

        return len(self.metrics)


 
# Representation Comparison

@dataclass(
    slots=True,
    frozen=True
)
class RepresentationComparison:
    """
    Comparison of multiple scientific representations.

    This object records the comparison results produced
    by a representation comparison algorithm.

    It stores the score assigned to each representation,
    the ranking of representations and the selected
    best representation.

    Notes
    -----
    Representation identifiers are used instead of
    Representation objects to avoid circular
    dependencies.
    """


    representation_scores: Mapping[
        str,
        float
    ]

    best_representation: str

    ranking: tuple[
        str,
        ...
    ]

    comparison_method: str = "default"

    comparison_version: tuple[int, int, int] = (
        1,
        0,
        0,
    )


    # ------------------------------------------------------

    @property
    def n_representations(
        self
    ) -> int:
        """
        Number of compared representations.
        """

        return len(self.representation_scores)