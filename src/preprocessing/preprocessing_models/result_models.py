"""
==========================================================
Representation Generation Layer (RGL)

Result models used by the preprocessing framework.

These dataclasses describe the complete output
generated while preprocessing one target.

Author : Shyam Girish Chinta
==========================================================
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from preprocessing.preprocessing_models.input_models import (
    FluxSelectionResult,
    PreprocessInput
)

from preprocessing.preprocessing_models.metrics_models import (
    RepresentationComparison,
    RepresentationMetrics
)

from preprocessing.preprocessing_models.representation_models import (
    Representation
)

from preprocessing.preprocessing_models.statistics_models import (
    ProcessingError,
    ProcessingStatistics,
    ProcessingWarning
)

from collections.abc import Mapping

import pandas as pd


 
# Preprocess Result

@dataclass(
    slots=True
)
class PreprocessResult:
    """
    Complete preprocessing result for a single target.

    This object aggregates every output generated by the
    preprocessing framework and acts as the interface
    between preprocessing and downstream pipeline stages.

    Notes
    -----
    This object is intentionally mutable because it is
    constructed progressively during pipeline execution.
    """

     
    # Input

    input: PreprocessInput

    flux_selection: FluxSelectionResult | None = None

    cleaned_dataframe: pd.DataFrame | None = None

     
    # Scientific Outputs

    representations: dict[
        str,
        Representation
    ] = field(
        default_factory=dict
    )

    representation_metrics: dict[
        str,
        RepresentationMetrics
    ] = field(
        default_factory=dict
    )

    comparison: RepresentationComparison | None = None

     
    # Processing Information

    statistics: ProcessingStatistics | None = None

    warnings: tuple[
        ProcessingWarning,
        ...
    ] = ()

    errors: tuple[
        ProcessingError,
        ...
    ] = ()

     
    # Output Files

    output_parquet: Path | None = None

    output_metadata: Path | None = None

     
    # Convenience Properties

    @property
    def n_representations(self) -> int:
        """
        Number of generated representations.
        """

        return len(self.representations)

    @property
    def n_metrics(self) -> int:
        """
        Number of evaluated representations.
        """

        return len(self.representation_metrics)

    @property
    def n_warnings(self) -> int:
        """
        Number of processing warnings.
        """

        return len(self.warnings)

    @property
    def n_errors(self) -> int:
        """
        Number of processing errors.
        """

        return len(self.errors)

    @property
    def has_errors(self) -> bool:
        """
        Returns True if preprocessing generated errors.
        """

        return self.n_errors > 0

    @property
    def has_warnings(self) -> bool:
        """
        Returns True if preprocessing generated warnings.
        """

        return self.n_warnings > 0

    @property
    def is_successful(self) -> bool:
        """
        Returns True if preprocessing completed
        without any errors.
        """

        return not self.has_errors

    @property
    def best_representation(self) -> Representation | None:
        """
        Returns the highest-ranked representation.

        Returns
        -------
        Representation | None
            The best representation if available,
            otherwise None.
        """

        if self.comparison is None:
            return None

        return self.representations.get(
            self.comparison.best_representation
        )

    @property
    def best_metrics(self) -> RepresentationMetrics | None:
        """
        Returns the evaluation metrics associated
        with the best representation.

        Returns
        -------
        RepresentationMetrics | None
            Metrics for the best representation if
            available, otherwise None.
        """

        if self.comparison is None:
            return None

        return self.representation_metrics.get(
            self.comparison.best_representation
        )